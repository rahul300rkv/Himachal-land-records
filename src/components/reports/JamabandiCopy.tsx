import { Document, Page, Text, View } from '@react-pdf/renderer';

export type JamabandiData = {
  receiptNumber: string;
  labels: { id: string; value: string }[];
  parcelTable: { headers: string[]; rows: string[][] };
};

export function JamabandiCopy({ data }: { data: JamabandiData }) {
  const values = new Map(data.labels.map(({ id, value }) => [id.replace(/^ctl00_ContentPlaceHolder1_/, ''), value]));
  const fields = [
    ['जिला', 'lblDis'], ['तहसील/उप-तहसील', 'lblTeh'],
    ['कानूनगो वृत', 'lblKanoongo'], ['पटवार वृत', 'lblPatwar'],
    ['हदबस्त नं.', 'lblHadbast'], ['राजस्व गांव', 'lblMohal'],
    ['जमाबंदी वर्ष', 'lblYear'], ['क्षेत्रफल इकाई', 'lblRakba'],
    ['खाता नम्बर', 'lblKhewat'], ['नम्बरदार का नाम व पत्ती', 'lblNaam'],
    ['भू-राजस्व एवं स्वाई', 'lblMutabla'], ['मालिक का पूर्ण विवरण', 'lblMalik'],
  ];
  const widths = ['12%', '23%', '11%', '10%', '16%', '13%', '15%'];
  return (
    <Document title="Jamabandi information copy" author="HimLand Check">
      <Page size="A4" orientation="landscape" style={{ fontFamily: ['Hind', 'HindDeva'], fontSize: 9, padding: 28, paddingBottom: 56, lineHeight: 1.35 }}>
        <Text style={{ fontSize: 15 }}>Jamabandi information copy — generated by HimLand Check</Text>
        <Text style={{ fontSize: 11, marginTop: 2 }}>राजस्व विभाग, हिमाचल प्रदेश — नकल जमाबन्दी</Text>
        <Text style={{ marginVertical: 5, fontSize: 8 }}>रसीद संख्या : {data.receiptNumber}</Text>
        <Text style={{ fontSize: 7.5, marginBottom: 8, color: '#444444' }}>यह प्रति केवल प्राप्त अभिलेख की सूचनात्मक प्रस्तुति है। प्रमाणित सरकारी प्रति के लिए HimBhoomi से मूल दस्तावेज प्राप्त करें।</Text>
        <View style={{ borderWidth: 0.6, borderColor: '#888888' }}>
          {[fields.slice(0, 8), fields.slice(8, 10)].map((row, rowIndex) => (
            <View key={rowIndex} style={{ flexDirection: 'row' }} wrap={false}>
              {row.map(([label, id]) => (
                <View key={id} style={{ width: rowIndex === 1 ? '50%' : '25%', flexDirection: 'row', borderRightWidth: 0.5, borderBottomWidth: 0.5, borderColor: '#aaaaaa', minHeight: 24 }}>
                  <Text style={{ width: '42%', padding: 3, fontSize: 7, backgroundColor: '#f1f2f3' }}>{label}</Text>
                  <Text style={{ width: '58%', padding: 3, fontSize: 8 }}>{values.get(id) || '—'}</Text>
                </View>
              ))}
            </View>
          ))}
          {fields.slice(10).map(([label, id]) => (
            <View key={id} style={{ flexDirection: 'row', borderBottomWidth: 0.5, borderColor: '#aaaaaa' }} wrap={false}>
              <Text style={{ width: '20%', padding: 3, fontSize: 7, backgroundColor: '#f1f2f3' }}>{label}</Text>
              <Text style={{ width: '80%', padding: 3, fontSize: 8 }}>{values.get(id) || '—'}</Text>
            </View>
          ))}
        </View>
        <View style={{ marginTop: 14 }}>
          <View style={{ flexDirection: 'row', backgroundColor: '#eef0f3' }} wrap={false}>
            {data.parcelTable.headers.map((header, index) => (
              <Text key={index} style={{ width: widths[index], padding: 4, borderWidth: 0.5, borderColor: '#bbbbbb' }}>{header}</Text>
            ))}
          </View>
          {data.parcelTable.rows.map((row, index) => (
            <View key={index} style={{ flexDirection: 'row' }}>
              {row.map((cell, column) => (
                <Text key={column} style={{ width: widths[column], padding: 4, borderWidth: 0.5, borderColor: '#dddddd' }}>{cell || ' '}</Text>
              ))}
            </View>
          ))}
        </View>
        <Text fixed style={{ position: 'absolute', bottom: 22, left: 28, right: 28, fontSize: 8 }} render={({ pageNumber, totalPages }) => `HimLand Check | Information copy | ${pageNumber} / ${totalPages}`} />
      </Page>
    </Document>
  );
}
